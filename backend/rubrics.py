"""국립국어원 논증적 글쓰기 채점 준거 (설계문서 확정 프레임).

총 9개 준거 × 1~5점 척도 (총점 범위 9~45점).
`글쓰기채점_문항_예시글_채점기준표_척도.txt`의 척도표를 요약하여
프롬프트에 주입 가능한 형태로 정리했다.
"""

NIKL_CRITERIA = [
    {"category": "내용", "label": "문제 상황 제시"},
    {"category": "내용", "label": "주장"},
    {"category": "내용", "label": "이유·근거의 적절성"},
    {"category": "내용", "label": "이유·근거의 충분성"},
    {"category": "내용", "label": "다른 입장에 대한 고려"},
    {"category": "조직", "label": "글 전체 조직"},
    {"category": "조직", "label": "문단 내 조직"},
    {"category": "표현", "label": "문장과 어휘"},
    {"category": "표현", "label": "어문 규범과 관습"},
]

NIKL_SCALE_NOTE = """
각 준거는 1~5점 척도로 평가한다 (5=매우 우수, 4=우수, 3=보통, 2=미흡, 1=매우 미흡).
- 문제 상황 제시: 문제 상황에 대한 이해가 논제와 얼마나 밀접하고 정보성 있게 제시되는가
- 주장: 주장이 논제에 부합하며 글 전체에서 일관되고 뚜렷한가
- 이유·근거의 적절성: 주장을 뒷받침하는 이유/근거가 적절하고 설득력이 있는가
- 이유·근거의 충분성: 하위 주장(이유)을 2가지 이상 제시하고 각각을 깊이 있게 전개했는가
- 다른 입장에 대한 고려: 다른 입장이 존재할 수 있음을 인식하고 그 내용을 깊이 있게 다루었는가
- 글 전체 조직: 서-본-결 구조가 적절히 구분되고 문단 배열이 유기적인가
- 문단 내 조직: 각 문단이 완결성·통일성·일관성을 갖추었는가
- 문장과 어휘: 문장이 자연스럽고 어휘 사용이 문맥에 맞으며 논증에 효과적인가
- 어문 규범과 관습: 맞춤법·띄어쓰기 등 어문 규범과 글쓰기 관습을 준수했는가
""".strip()


def nikl_rubric_text() -> str:
    lines = [f"- [{c['category']}] {c['label']} (1~5점)" for c in NIKL_CRITERIA]
    return (
        "국립국어원 논증적 글쓰기 채점 준거 (총 9개, 각 1~5점, 총점 범위 9~45점):\n"
        + "\n".join(lines)
        + "\n\n"
        + NIKL_SCALE_NOTE
    )
